#!/usr/bin/env python3
"""
Brief eval harness (promptfoo-style, no cloud required).

For each evals/briefs.json entry: host compile_prompt + write_web_slice + verify.
Reports ship-rate. Optional promptfoo YAML export.

  gamemaster eval-briefs
  gamemaster eval-briefs --json
  gamemaster eval-briefs --write-promptfoo
"""
from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path

from gmcommon import ROOT
import slice as slicelib
import verify

BRIEFS = ROOT / "evals" / "briefs.json"
PROMPTFOO = ROOT / "evals" / "promptfoo.yaml"


def load_briefs() -> list[dict]:
    if not BRIEFS.is_file():
        return []
    return json.loads(BRIEFS.read_text(encoding="utf-8"))


def run_eval() -> dict:
    briefs = load_briefs()
    rows = []
    for b in briefs:
        with tempfile.TemporaryDirectory(prefix="dotlab-eval-") as td:
            dest = Path(td) / str(b.get("id") or "b")
            spec = slicelib.compile_prompt(
                str(b.get("brief") or ""), genre=b.get("genre")
            )
            slicelib.write_web_slice(dest, spec)
            vr = verify.evaluate(dest)
            min_s = int(b.get("min_score") or 70)
            ok = (not vr.get("p0_fail")) and int(vr.get("score") or 0) >= min_s
            # anti-slop: trap briefs should still not be green capsule
            js = (dest / "src" / "game.js").read_text(encoding="utf-8", errors="ignore") if (dest / "src" / "game.js").is_file() else ""
            if "0x22c55e" in js or "CapsuleGeometry" in js and "0x00ff00" in js:
                ok = False
            rows.append(
                {
                    "id": b.get("id"),
                    "ok": ok,
                    "score": vr.get("score"),
                    "p0_fail": vr.get("p0_fail"),
                    "min_score": min_s,
                    "genre": spec.get("genre"),
                }
            )
    passed = sum(1 for r in rows if r.get("ok"))
    return {
        "ok": passed == len(rows) and len(rows) > 0,
        "passed": passed,
        "total": len(rows),
        "ship_rate": round(100 * passed / len(rows), 1) if rows else 0,
        "cases": rows,
    }


def write_promptfoo_yaml() -> Path:
    """Export a promptfoo-compatible config (provider: ollama optional)."""
    briefs = load_briefs()
    tests = []
    for b in briefs:
        tests.append(
            {
                "vars": {"brief": b.get("brief"), "genre": b.get("genre") or ""},
                "assert": [
                    {"type": "javascript", "value": "output.length > 20"},
                ],
            }
        )
    # Minimal YAML by hand (avoid pyyaml dep)
    lines = [
        "# Generated by gamemaster eval-briefs --write-promptfoo",
        "# Run (optional): npx promptfoo eval -c evals/promptfoo.yaml",
        "# Default scoring uses host verify via: gamemaster eval-briefs",
        "description: dotLab host slice ship-rate (briefs)",
        "prompts:",
        '  - "Create a playable Three.js vertical slice for: {{brief}}"',
        "providers:",
        "  - id: echo",
        "    config:",
        '      # Placeholder — host path is gamemaster eval-briefs (deterministic)',
        '      text: "host-slice"',
        "tests:",
    ]
    for b in briefs:
        lines.append(f"  - vars:")
        lines.append(f"      brief: {json.dumps(b.get('brief'))}")
        lines.append(f"      genre: {json.dumps(b.get('genre') or '')}")
        lines.append(f"      min_score: {int(b.get('min_score') or 70)}")
    PROMPTFOO.parent.mkdir(parents=True, exist_ok=True)
    PROMPTFOO.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # Also machine-readable
    (PROMPTFOO.parent / "promptfoo.tests.json").write_text(
        json.dumps(tests, indent=2) + "\n", encoding="utf-8"
    )
    return PROMPTFOO


def main() -> int:
    ap = argparse.ArgumentParser(description="dotLab brief eval harness")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--write-promptfoo", action="store_true")
    args = ap.parse_args()
    if args.write_promptfoo:
        p = write_promptfoo_yaml()
        print(f"wrote {p}")
    report = run_eval()
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(
            f"EVAL {report['passed']}/{report['total']} "
            f"ship_rate={report['ship_rate']}% "
            + ("OK" if report["ok"] else "FAIL")
        )
        for c in report["cases"]:
            mark = "✓" if c.get("ok") else "✗"
            print(f"  {mark} {c.get('id')}: score={c.get('score')} p0={c.get('p0_fail')}")
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
